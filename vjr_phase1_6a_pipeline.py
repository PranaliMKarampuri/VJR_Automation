#!/usr/bin/env python3
"""Build the Phase 1–5 integrated workbook plus explicit Phase 6A spiral MBD.

Phase 1–5 values are generated by the existing pipeline unchanged. The
Phase 6A transform is then applied only to matched SPIRALE!M diameter rows.
No topology-based damper inference is performed.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import tempfile
import warnings
import zipfile
from decimal import Decimal
from pathlib import Path
from typing import Any
from xml.etree import ElementTree as ET

from openpyxl import load_workbook

import rectangular_duct_takeoff as rectangular
import spiral_damper_takeoff as spiral_damper
import spiral_duct_takeoff as spiral
import vjr_phase1_5_pipeline as phase1_5


ROOT = Path(__file__).resolve().parent
DEFAULT_TEMPLATE = phase1_5.DEFAULT_TEMPLATE
DEFAULT_PHASE2_INPUT = phase1_5.DEFAULT_PHASE2_INPUT
DEFAULT_PHASE3_INPUT = phase1_5.DEFAULT_PHASE3_INPUT
DEFAULT_PHASE4_INPUT = phase1_5.DEFAULT_PHASE4_INPUT
DEFAULT_PHASE5_INPUT = phase1_5.DEFAULT_PHASE5_INPUT
DEFAULT_PHASE6A_INPUT = spiral_damper.DEFAULT_INPUT
DEFAULT_OUTPUT = ROOT / "output" / "Ventilation Jean Roy - phases 1-6A integrated.xlsx"
DEFAULT_REPORT = ROOT / "output" / "phase1_6a_integration_validation_report.txt"

TAKEOFF = phase1_5.TAKEOFF
SPIRAL = phase1_5.SPIRAL
ROUND_FLEX = phase1_5.ROUND_FLEX
NS_MAIN = phase1_5.NS_MAIN


class PipelineValidationError(Exception):
    def __init__(self, errors: list[str]):
        self.errors = errors
        super().__init__("Phase 1–6A integration validation failed")


def _safe_value(value: Any) -> str:
    return "<blank>" if value is None else str(value)


def _compare_value(actual: Any, expected: Any) -> bool:
    if isinstance(expected, Decimal):
        try:
            return float(actual) == float(expected)
        except Exception:
            return False
    return actual == expected


def _xml_child_bytes(root: ET.Element, tag: str) -> bytes | None:
    node = root.find(f"{{{NS_MAIN}}}{tag}")
    return ET.tostring(node, encoding="utf-8") if node is not None else None


def generate(
    template: Path = DEFAULT_TEMPLATE,
    phase2_csv: Path = DEFAULT_PHASE2_INPUT,
    phase3_csv: Path = DEFAULT_PHASE3_INPUT,
    phase4_csv: Path = DEFAULT_PHASE4_INPUT,
    phase5_csv: Path = DEFAULT_PHASE5_INPUT,
    phase6a_csv: Path = DEFAULT_PHASE6A_INPUT,
    output: Path = DEFAULT_OUTPUT,
) -> list[str]:
    """Generate and validate a single workbook containing Phase 1–5 + 6A."""
    if not template.is_file():
        raise PipelineValidationError([f"Template not found: {template}"])
    if template.resolve() == output.resolve():
        raise PipelineValidationError(["Output must not overwrite the original VJR template"])

    source_hash_before = hashlib.sha256(template.read_bytes()).hexdigest()
    p1_values, p1_counts, _ = phase1_5.build_input_maps(
        template, phase2_csv, phase3_csv, phase4_csv, phase5_csv
    )
    damper_records, errors = spiral_damper.read_records(phase6a_csv)
    if errors:
        raise PipelineValidationError(["Phase 6A spiral damper input: " + error for error in errors])
    damper_values, errors = spiral_damper.build_values(damper_records, template)
    if errors:
        raise PipelineValidationError(["Phase 6A spiral damper mapping: " + error for error in errors])
    if any(not (spiral.DIAMETER_FIRST_ROW <= int(cell[1:]) <= spiral.DIAMETER_LAST_ROW)
           or not cell.startswith("M") for cell in damper_values):
        raise PipelineValidationError(["Phase 6A mapping attempted to write outside SPIRALE!M11:M63"])

    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="vjr-phase1-6a-") as temp_dir:
        phase1_5_output = Path(temp_dir) / "phase1_5_intermediate.xlsx"
        phase1_5_lines = phase1_5.generate(
            template, phase2_csv, phase3_csv, phase4_csv, phase5_csv, phase1_5_output
        )
        # Reuse Phase 6A's package patcher to add only explicit M-cell values
        # to the already validated Phase 1–5 workbook.
        spiral_damper.spiral._write_package_preserving_template(
            phase1_5_output, output, damper_values
        )

    source_hash_after = hashlib.sha256(template.read_bytes()).hexdigest()
    if source_hash_before != source_hash_after:
        raise RuntimeError("Original VJR template SHA-256 changed during generation")

    with zipfile.ZipFile(template, "r") as source_zip, zipfile.ZipFile(output, "r") as output_zip:
        if set(source_zip.namelist()) != set(output_zip.namelist()):
            raise RuntimeError("Integrated workbook package members differ from the template")
        parts = {
            TAKEOFF: phase1_5._sheet_part(source_zip, TAKEOFF),
            SPIRAL: phase1_5._sheet_part(source_zip, SPIRAL),
            ROUND_FLEX: phase1_5._sheet_part(source_zip, ROUND_FLEX),
        }
        changed_parts = [name for name in sorted(source_zip.namelist())
                         if source_zip.read(name) != output_zip.read(name)]
        if changed_parts != sorted(parts.values()):
            raise RuntimeError(f"Unexpected workbook package changes: {changed_parts}")
        if output_zip.testzip() is not None:
            raise RuntimeError("Integrated XLSX ZIP integrity check failed")
        for sheet_name, part in parts.items():
            source_root = ET.fromstring(source_zip.read(part))
            output_root = ET.fromstring(output_zip.read(part))
            for tag in ("dataValidations", "extLst"):
                if _xml_child_bytes(source_root, tag) != _xml_child_bytes(output_root, tag):
                    raise RuntimeError(f"{sheet_name} {tag} XML changed")

    formulas_before = rectangular._formula_map(template)
    formulas_after = rectangular._formula_map(output)
    p1_written = {(sheet_name, cell) for sheet_name, cells in p1_values.items() for cell in cells}
    p6_written = {(SPIRAL, cell) for cell in damper_values}
    expected_formulas = {
        key: formula for key, formula in formulas_before.items()
        if key not in (p1_written | p6_written)
    }
    if formulas_after != expected_formulas:
        raise RuntimeError("Formula preservation failed outside explicit input cells")
    if rectangular._takeoff_calculation_formulas(formulas_before) != rectangular._takeoff_calculation_formulas(formulas_after):
        raise RuntimeError("TAKE OFF K:AX calculation formulas changed")
    for sheet_name in (SPIRAL, ROUND_FLEX):
        before = {key: formula for key, formula in formulas_before.items() if key[0] == sheet_name}
        after = {key: formula for key, formula in formulas_after.items() if key[0] == sheet_name}
        if before != after:
            raise RuntimeError(f"Formula preservation failed on {sheet_name}")

    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="Data Validation extension is not supported")
        source_book = load_workbook(template, data_only=False, read_only=False)
        output_book = load_workbook(output, data_only=False, read_only=False)
    if source_book.sheetnames != output_book.sheetnames:
        raise RuntimeError("Worksheet structure changed")
    for sheet_name in source_book.sheetnames:
        source_sheet, output_sheet = source_book[sheet_name], output_book[sheet_name]
        if set(map(str, source_sheet.merged_cells.ranges)) != set(map(str, output_sheet.merged_cells.ranges)):
            raise RuntimeError(f"Merged ranges changed in {sheet_name}")
        if len(source_sheet._images) != len(output_sheet._images):
            raise RuntimeError(f"Drawing/image count changed in {sheet_name}")
        if sheet_name not in parts:
            continue
        sheet_inputs = dict(p1_values.get(sheet_name, {}))
        if sheet_name == SPIRAL:
            sheet_inputs.update(damper_values)
        for row in source_sheet.iter_rows():
            for cell in row:
                output_cell = output_sheet[cell.coordinate]
                if cell.coordinate not in sheet_inputs and output_cell.value != cell.value:
                    raise RuntimeError(f"Unexpected value change at {sheet_name}!{cell.coordinate}")
                if output_cell.style_id != cell.style_id:
                    raise RuntimeError(f"Style changed at {sheet_name}!{cell.coordinate}")
        for coordinate, expected in sheet_inputs.items():
            if not _compare_value(output_sheet[coordinate].value, expected):
                raise RuntimeError(
                    f"Output mismatch at {sheet_name}!{coordinate}: "
                    f"{output_sheet[coordinate].value!r} != {expected!r}"
                )

    input_lines = [line for line in phase1_5_lines if line.startswith("EXACT INPUT CELLS:")]
    p6_cell_list = ", ".join(f"{cell}={value}" for cell, value in damper_values.items()) or "none"
    report_lines = [
        "PASS: reused the existing Phase 1–5 integration generator without modifying its source or transformation scripts.",
        f"PASS: Phase 1–5 inputs preserved: {p1_counts['phase2_source_rows']} Phase 1–2 rectangular rows, "
        f"{p1_counts['phase3_spiral_rows']} Phase 3 spiral diameter rows, Phase 4 input mapping, and "
        f"{p1_counts['phase5_rectangular_rows']} rectangular plus {p1_counts['phase5_spiral_rows']} spiral Phase 5 riser rows.",
        *input_lines,
        f"PASS: Phase 6A validated {len(damper_records)} explicit damper records using Phase 3 exact diameter matching; repeated inch/metric matches aggregate without rounding.",
        f"PHASE 6A INPUT CELLS ADDED: SPIRALE: {p6_cell_list}.",
        "PASS: no inference from branches, GRD connections, VAV boxes, valves or drawing topology was applied.",
        f"PASS: preserved all {len(rectangular._takeoff_calculation_formulas(formulas_before)):,} TAKE OFF K:AX calculation formulas exactly.",
        f"PASS: preserved all {sum(1 for (sheet, _) in formulas_before if sheet == SPIRAL):,} SPIRALE formulas and all {sum(1 for (sheet, _) in formulas_before if sheet == ROUND_FLEX):,} ROND ET FLEX formulas; remaining workbook formulas match exactly outside explicitly written inputs.",
        f"PASS: workbook opens; worksheet names/count, styles, merged cells, drawing counts and ZIP integrity verified. Only {', '.join(sorted(parts.values()))} differ from the original template.",
        "PASS: validations and extension XML are unchanged on edited sheets; all other workbook package parts are byte-identical to the original template.",
        f"PASS: original template SHA-256 unchanged ({source_hash_after}).",
        "LIMITATION: existing Phase 1–5 carry-down behavior remains unchanged; independent rectangular/riser values replace carry-down formulas in populated input cells as documented by Phase 1–5.",
        "NOT CHECKED: formula recalculation. No Excel/LibreOffice calculation engine was available or used.",
        f"OUTPUT: {output}",
    ]
    return report_lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--template", type=Path, default=DEFAULT_TEMPLATE)
    parser.add_argument("--phase2-input", type=Path, default=DEFAULT_PHASE2_INPUT)
    parser.add_argument("--phase3-input", type=Path, default=DEFAULT_PHASE3_INPUT)
    parser.add_argument("--phase4-input", type=Path, default=DEFAULT_PHASE4_INPUT)
    parser.add_argument("--phase5-input", type=Path, default=DEFAULT_PHASE5_INPUT)
    parser.add_argument("--phase6a-input", type=Path, default=DEFAULT_PHASE6A_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args()
    try:
        lines = generate(
            args.template, args.phase2_input, args.phase3_input, args.phase4_input,
            args.phase5_input, args.phase6a_input, args.output,
        )
    except (PipelineValidationError, phase1_5.PipelineValidationError,
            spiral_damper.InputValidationError) as exc:
        print("VALIDATION FAILED")
        for error in exc.errors:
            print(f"ERROR: {error}")
        return 2
    except Exception as exc:
        print(f"GENERATION FAILED: {exc}", file=sys.stderr)
        return 1
    report = "PHASE 1–5 + 6A INTEGRATION VALIDATION REPORT\n" + "\n".join(lines) + "\n"
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(report, encoding="utf-8")
    print(report, end="")
    print(f"REPORT: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
